    private JF_VPMT_mxJPO(Context context){
        try {
            log.info("create JF_VPMT_mxJPO");
            StringList partypelist = FrameworkUtil.getRanges(context, ATTRIBUTE_PARTTYPE);
            locks = new ConcurrentHashMap<>();
            sequenceNumbers = new ConcurrentHashMap<>();
            for (String partype : partypelist) {
                if(UIUtil.isNotNullAndNotEmpty(partype)) {
                    locks.put(partype, new ReentrantLock());
                    sequenceNumbers.put(partype, 0L);
                }
            }
            //竞品类型
            locks.put("BM", new ReentrantLock());
            sequenceNumbers.put("BM", 0L);
        }catch (Exception e){
            e.printStackTrace();
        }
    }
    public static JF_VPMT_mxJPO getInstance(Context context) {
        if(instance==null){
            synchronized (JF_VPMT_mxJPO.class){
                if(instance==null) {
                    instance = new JF_VPMT_mxJPO(context);
                }
            }
        }
        return instance;
    }

    public String autoName_old(Context context, DomainObject part,String code) throws FrameworkException {
        ReentrantLock lock = locks.get(code);
        lock.lock();
        String partName = "";
        try {
            //partName = DomainObject.getAutoGeneratedName(context, TYPE_JFDATATRANSMISSION + code, "");
            String val = MqlUtil.mqlCommand(context,"print bus 'eService Number Generator' '"+TYPE_JFDATATRANSMISSION + code+"' '' select attribute[eService Next Number].value dump;");
            String prefixval = MqlUtil.mqlCommand(context,"print bus 'eService Object Generator' '"+TYPE_JFDATATRANSMISSION + code+"' '' select attribute[eService Name Prefix].value dump;");
            partName = prefixval+val;
            int len = val.length();
            int nextNum = Integer.parseInt(val);
            nextNum += 1;
            String nextNumber  = String.format("%"+len+"s", nextNum+"").replace(' ', '0');
            MqlUtil.mqlCommand(context,"mod bus 'eService Number Generator' '"+TYPE_JFDATATRANSMISSION + code+"' ''  'eService Next Number' "+nextNumber+";");
        }catch (Exception e){
            log.error(e.getMessage());
            e.printStackTrace();
        }finally {
            lock.unlock();
        }
        return partName;
        //part.setAttributeValue(context,ATTRIBUTE_PARTNUMBER,partName);
    }

