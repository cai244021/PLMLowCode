    String ATTRIBUTE_PARTTYPE = "JF_VPMReference.JF_PartType";
    private static JF_VPMT_mxJPO instance =null;
    private ConcurrentHashMap<String, ReentrantLock> locks;
    private ConcurrentHashMap<String, Long> sequenceNumbers;
